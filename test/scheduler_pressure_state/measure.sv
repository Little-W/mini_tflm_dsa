module ps_scheduler_pressure_measure #(
    parameter int unsigned SIZE = 16,
    parameter int unsigned FRAME_COUNT = 16,
    parameter int unsigned MAX_REUSE_TILES = 0
) (
    input logic clk, rst_n,
    input logic start,
    input logic [31:0] stream_rows, stationary_rows, reduction,
    input logic [31:0] reuse_rows, window_frames,
    input logic [31:0] slice_tiles = 32'd0,
    input logic [1:0] config_error,
    output logic ready,
    output logic done_valid,
    input logic done_ready,
    output logic [1:0] err_code,
    output logic command_valid,
    input logic command_ready,
    input logic command_pressure,
    input logic command_complete,
    output logic [((FRAME_COUNT > 1) ? $clog2(FRAME_COUNT) : 1)-1:0] frame_id,
    output logic [31:0] p0, q0, column0, rows, cols, count_k, reserve_rows,
    output logic frame_init, frame_final,
    output logic command_active,
    output logic lookahead_valid,
    output logic [31:0] lookahead_q0, lookahead_column, lookahead_cols, lookahead_count_k);
    logic pressure_sampled;
    always_ff @(posedge clk) pressure_sampled <= command_pressure;
    ps_window_scheduler #(.SIZE(SIZE),.FRAME_COUNT(FRAME_COUNT),.MAX_REUSE_TILES(MAX_REUSE_TILES)) dut (
        .clk(clk),
        .rst_n(rst_n),
        .start(start),
        .stream_rows(stream_rows),
        .stationary_rows(stationary_rows),
        .reduction(reduction),
        .reuse_rows(reuse_rows),
        .window_frames(window_frames),
        .slice_tiles(slice_tiles),
        .config_error(config_error),
        .ready(ready),
        .done_valid(done_valid),
        .done_ready(done_ready),
        .err_code(err_code),
        .command_valid(command_valid),
        .command_ready(command_ready),
        .command_pressure(pressure_sampled),
        .command_complete(command_complete),
        .frame_id(frame_id),
        .p0(p0),
        .q0(q0),
        .column0(column0),
        .rows(rows),
        .cols(cols),
        .count_k(count_k),
        .reserve_rows(reserve_rows),
        .frame_init(frame_init),
        .frame_final(frame_final),
        .command_active(command_active),
        .lookahead_valid(lookahead_valid),
        .lookahead_q0(lookahead_q0),
        .lookahead_column(lookahead_column),
        .lookahead_cols(lookahead_cols),
        .lookahead_count_k(lookahead_count_k)
    );
endmodule
